alter table public.wishlist    enable row level security;

-- ---------- profiles ----------
drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles
    for select using (auth.uid() = id or public.is_admin());

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles
    for update using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists profiles_admin_all on public.profiles;
create policy profiles_admin_all on public.profiles
    for all using (public.is_admin()) with check (public.is_admin());

-- ---------- products ----------
drop policy if exists products_read_all on public.products;
create policy products_read_all on public.products
    for select using (true);

drop policy if exists products_admin_write on public.products;
create policy products_admin_write on public.products
    for insert with check (public.is_admin());

drop policy if exists products_admin_update on public.products;
create policy products_admin_update on public.products
    for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists products_admin_delete on public.products;
create policy products_admin_delete on public.products
    for delete using (public.is_admin());

-- ---------- addresses ----------
drop policy if exists addresses_owner_all on public.addresses;
create policy addresses_owner_all on public.addresses
    for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ---------- orders ----------
drop policy if exists orders_insert_any on public.orders;
create policy orders_insert_any on public.orders
    for insert with check (user_id is null or user_id = auth.uid());

drop policy if exists orders_select_own_or_admin on public.orders;
create policy orders_select_own_or_admin on public.orders
    for select using (user_id = auth.uid() or public.is_admin());

-- customer may cancel their own order that has not been delivered yet
drop policy if exists orders_cancel_own on public.orders;
create policy orders_cancel_own on public.orders
    for update using (user_id = auth.uid() and status in ('Processing', 'Shipped'))
    with check (user_id = auth.uid() and status = 'Cancelled');

-- admin may change any order (including status)
drop policy if exists orders_admin_update on public.orders;
create policy orders_admin_update on public.orders
    for update using (public.is_admin()) with check (public.is_admin());

-- ---------- order items ----------
drop policy if exists order_items_insert_any on public.order_items;
create policy order_items_insert_any on public.order_items
    for insert with check (true);

drop policy if exists order_items_select_owner on public.order_items;
create policy order_items_select_owner on public.order_items
    for select using (
        exists (
            select 1 from public.orders o
            where o.id = order_items.order_id
              and (o.user_id = auth.uid() or public.is_admin())
        )
    );

-- ---------- wishlist ----------
drop policy if exists wishlist_owner_all on public.wishlist;
create policy wishlist_owner_all on public.wishlist
    for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

