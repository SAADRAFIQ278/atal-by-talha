create extension if not exists pgcrypto;

-- ----------------------------------------------------------------------------
-- 1. PROFILES  (one row per auth user + role)
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
    id          uuid primary key references auth.users (id) on delete cascade,
    name        text        not null default '',
    email       text        not null,
    phone       text        not null default '',
    role        text        not null default 'customer' check (role in ('customer', 'admin')),
    created_at  timestamptz not null default now()
);

-- Create a profile automatically whenever someone signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, name, email, phone)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'name', ''),
        new.email,
        coalesce(new.raw_user_meta_data ->> 'phone', '')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- Admin helper used by every policy below (security definer => no RLS recursion).
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.profiles p
        where p.id = auth.uid() and p.role = 'admin'
    );
$$;

-- Customers must never be able to promote themselves.
create or replace function public.guard_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.role is distinct from old.role and not public.is_admin() then
        raise exception 'Only administrators can change account roles';
    end if;
    return new;
end;
$$;

drop trigger if exists profiles_guard_role on public.profiles;
create trigger profiles_guard_role
    before update on public.profiles
    for each row execute function public.guard_profile_role();

-- ----------------------------------------------------------------------------
-- 2. PRODUCTS  (leather boots catalogue)
-- ----------------------------------------------------------------------------
create table if not exists public.products (
    id          bigint generated by default as identity primary key,
    name        text        not null,
    category    text        not null check (category in ('Chelsea', 'Chukka', 'Combat', 'Formal', 'Hiking')),
    price       integer     not null check (price >= 0),
    old_price   integer     not null default 0,
    badge       text        not null default '',
    rating      numeric(2,1) not null default 0,
    reviews     integer     not null default 0,
    stock       integer     not null default 0,
    material    text        not null default '',
    sole        text        not null default '',
    description text        not null default '',
    sizes       text[]      not null default array['6','7','8','9','10','11','12'],
    colors      jsonb       not null default '[]'::jsonb,
    images      text[]      not null default '{}',
    is_active   boolean     not null default true,
    created_at  timestamptz not null default now()
);

create index if not exists products_category_idx on public.products (category);
create index if not exists products_created_idx  on public.products (created_at desc);

-- ----------------------------------------------------------------------------
-- 3. ADDRESSES  (saved delivery addresses)
-- ----------------------------------------------------------------------------
create table if not exists public.addresses (
    id          bigint generated by default as identity primary key,
    user_id     uuid        not null references auth.users (id) on delete cascade,
    label       text        not null default 'Home',
    name        text        not null,
    phone       text        not null default '',
    address     text        not null,
    city        text        not null default '',
    postal      text        not null default '',
    is_default  boolean     not null default false,
    created_at  timestamptz not null default now()
);

create index if not exists addresses_user_idx on public.addresses (user_id);

-- ----------------------------------------------------------------------------
-- 4. ORDERS  (id format matches the storefront: ATL-10482)
-- ----------------------------------------------------------------------------
create sequence if not exists public.order_number_seq start with 10480;

create table if not exists public.orders (
    id          text primary key default ('ATL-' || nextval('public.order_number_seq')::text),
    user_id     uuid        references auth.users (id) on delete set null,
    user_email  text        not null default '',
    user_name   text        not null default '',
    phone       text        not null default '',
    address     text        not null default '',
    city        text        not null default '',
    postal      text        not null default '',
    note        text        not null default '',
    subtotal    integer     not null default 0,
    shipping    integer     not null default 0,
    total       integer     not null default 0,
    payment     text        not null default 'COD',
    status      text        not null default 'Processing'
                            check (status in ('Processing', 'Shipped', 'Delivered', 'Cancelled')),
    created_at  timestamptz not null default now()
);

create index if not exists orders_user_idx    on public.orders (user_id);
create index if not exists orders_created_idx on public.orders (created_at desc);
create index if not exists orders_status_idx  on public.orders (status);

-- ----------------------------------------------------------------------------
-- 5. ORDER ITEMS  (line snapshots so history survives product edits)
-- ----------------------------------------------------------------------------
create table if not exists public.order_items (
    id          bigint generated by default as identity primary key,
    order_id    text    not null references public.orders (id) on delete cascade,
    product_id  bigint  references public.products (id) on delete set null,
    name        text    not null,
    image       text    not null default '',
    price       integer not null default 0,
    qty         integer not null default 1 check (qty > 0),
    size        text    not null default '',
    color       text    not null default ''
);

create index if not exists order_items_order_idx on public.order_items (order_id);

-- ----------------------------------------------------------------------------
-- 6. WISHLIST
-- ----------------------------------------------------------------------------
create table if not exists public.wishlist (
    user_id     uuid        not null references auth.users (id) on delete cascade,
    product_id  bigint      not null references public.products (id) on delete cascade,
    created_at  timestamptz not null default now(),
    primary key (user_id, product_id)
);

